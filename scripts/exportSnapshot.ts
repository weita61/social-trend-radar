import { writeFileSync, mkdirSync } from 'node:fs';
import { openDatabase } from '../src/db/database.ts';
import { AnalysisReadRepository } from '../src/analysis/readRepository.ts';

export function exportSnapshot(): void {
  const db = openDatabase();
  try {
    const repo = new AnalysisReadRepository(db);

    const snapshot = {
      exportedAt: new Date().toISOString(),
      overview: repo.getOverview(),
      trends: repo.listTrends({ layer: 'format' }).map((t) => {
        const full = repo.getTrend(String(t.id));
        return full ?? t;
      }),
      videos: repo.listVideos(),
      coverage: repo.getCoverage(),
      automation: repo.getAutomation(),
      pipeline: repo.getPipeline(),
      brandProfile: repo.getBrandProfile(),
    };

    mkdirSync('./src/data', { recursive: true });
    writeFileSync('./src/data/seedSnapshot.json', JSON.stringify(snapshot, null, 2), 'utf-8');

    const tsContent = `// Auto-generated by scripts/exportSnapshot.ts - do not edit directly
export const snapshotData = ${JSON.stringify(snapshot, null, 2)};
export default snapshotData;
`;
    writeFileSync('./src/data/seedSnapshot.ts', tsContent, 'utf-8');
    console.log(`[Snapshot] Successfully exported ${snapshot.videos.length} videos and ${snapshot.trends.length} trend formats to src/data/seedSnapshot.ts and .json`);
  } finally {
    db.close();
  }
}

if (import.meta.url === `file://${process.argv[1]}`) {
  exportSnapshot();
}
